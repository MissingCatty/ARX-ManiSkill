import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { readVersions } from '../版本树.mjs';

const site=JSON.parse(readFileSync(new URL('../内容/网站.json',import.meta.url),'utf8'));
const versions=site.versions.filter(v=>!v.experimentOwner&&!v.archived);
const owner=id=>site.versions.find(v=>v.id===id)?.experimentOwner??id;
const records=[...site.records,...site.versions.filter(v=>v.experimentOwner||v.archived)].map(v=>({...v,parent:v.experimentOwner??owner(v.parent)}));
const tree=readVersions(versions,records);
const roots=[...tree.nodes.values()].filter(v=>v.parent===null);
assert.deepEqual(roots.map(v=>v.id),['baseline','sam3-graspgenx']);
assert(roots.every(v=>v.type==='main'));
assert(tree.rows.at(-1).includes(tree.nodes.get('baseline')));
assert(tree.rows.at(-1).includes(tree.nodes.get('sam3-graspgenx')));
assert(!tree.nodes.has('graspgen'));
assert.equal(tree.nodes.get('occlusion-handling').parent,'baseline');
assert.equal(tree.nodes.get('reachability-improvement').parent,'baseline');
assert(!site.versions.some(v=>v.id==='joint9'));
assert.deepEqual(tree.nodes.get('sam3-graspgenx').children.map(v=>v.id),['pointcloud-models']);
assert.equal(tree.nodes.get('pointcloud-models').type,'experiment');
assert.equal(tree.nodes.get('pointcloud-models').parent,'sam3-graspgenx');
assert(roots[0].start+roots[0].span<=roots[1].start);
const entry=(id,parent=null,type='main')=>({id,parent,type,title:id,status:'test',date:'2026-11-22',summary:'test',file:id+'.md'});
const third=readVersions([entry('first'),entry('second'),entry('third'),entry('child','second','experiment')],[]);
assert.equal(third.rows.at(-1).length,3);
assert.equal(third.nodes.get('second').children[0].id,'child');
assert.throws(()=>readVersions([entry('root',null,'experiment')],[]),/主版本/);
assert.throws(()=>readVersions([entry('root'),entry('orphan','missing','experiment')],[]),/未登记父版本/);
assert.throws(()=>readVersions([entry('root'),entry('a','b','experiment'),entry('b','a','experiment')],[]),/循环继承/);
assert.throws(()=>readVersions([entry('a'),entry('a')],[]),/重复/);
console.log('并列主线核验通过：同层双主根、原继承保留、移除旧分支、后续第三主线、无效根／孤儿／循环与重复拒绝');
